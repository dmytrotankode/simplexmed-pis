def load_tree():
    with open(os.path.join(WEB, "tv-tree.json"), encoding="utf-8") as f:
        return {n["id"]: n for n in json.load(f)["nodes"]}


def covered(tree, prefixes):
    out = set()
    for p in prefixes:
        out.update(i for i in tree if i == p or i.startswith(p + "."))
    return out


def main():
    tree = load_tree()
    leaves = {i for i, n in tree.items() if n["applies"] and not any(m["parent"] == i for m in tree.values())}
    scenarios, seen, bad = [], set(), []
    cov = set()
    for sid, title, covers, where, steps, expect, platforms in S:
        if sid in seen:
            bad.append(f"повтор id {sid}")
        seen.add(sid)
        for c in covers:
            if c not in tree:
                bad.append(f"{sid}: невідомий пункт ТВ {c}")
        cov |= covered(tree, covers)
        scenarios.append({"id": sid, "title": title, "covers": covers, "where": where, "steps": steps,
                          "expect": expect, "platforms": platforms})
    if bad:
        print("ПОМИЛКИ:\n  " + "\n  ".join(bad))
        return 1
    uncovered = sorted((leaves - cov), key=lambda s: [int(p) for p in s.split(".")])
    with open(os.path.join(WEB, "scenarios.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump({"scenarios": scenarios}, f, ensure_ascii=False, indent=1)
    print(f"сценаріїв: {len(scenarios)}; листків ТВ: {len(leaves)}; покрито: {len(leaves & cov)}; непокрито: {len(uncovered)}")
    if uncovered:
        print("непокриті:", ", ".join(uncovered[:60]), "..." if len(uncovered) > 60 else "")
    return 0


if __name__ == "__main__":
    sys.exit(main())
