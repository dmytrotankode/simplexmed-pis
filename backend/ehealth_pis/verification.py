def verification_view(verification_data, patient_age=None, support_url=None):
    """
    verification_data — data з "PIS. Get Person verification details".
    Повертає {"items": [...], "documents_required": bool} для показу Користувачу.
    """
    details = ((verification_data or {}).get("person_verification") or {}).get("details") or {}
    items = []
    documents_required = False
    for key, label in DIRECTIONS.items():
        item = details.get(key)
        if not isinstance(item, dict):
            continue
        status = str(item.get("verification_status") or "").upper()
        reason = item.get("verification_reason")
        if key == "dracs_death" and status != "NOT_VERIFIED":
            continue   # п.3.9.3.3
        if key == "dracs_birth" and (status == "VERIFICATION_NOT_NEEDED" or
                                     (patient_age is not None and patient_age >= FULL_LEGAL_CAPACITY_AGE)):
            continue   # п.3.9.3.4.1
        message = MESSAGES[key].get(status, "")
        if key == "nhs" and status == "NOT_VERIFIED":
            if str(reason or "").upper() == "DOCUMENTS_TRIGGERED":
                message = MESSAGES["nhs"]["DOCUMENTS_TRIGGERED"]
                documents_required = True   # п.3.9.3.5.f: передача копій документів (п.3.6)
            else:
                message = message.format(comment=item.get("verification_comment") or "")
        if support_url:
            message = message.replace(SUPPORT_URL_PLACEHOLDER, support_url)
        show_comment = key in ("dracs_death",) or (key == "dracs_birth" and status == "NOT_VERIFIED")
        items.append({
            "direction": key,
            "label": label,
            "status": status,
            "reason": reason,
            "comment": item.get("verification_comment") if show_comment else None,
            "message": message,
        })
    return {"items": items, "documents_required": documents_required}
